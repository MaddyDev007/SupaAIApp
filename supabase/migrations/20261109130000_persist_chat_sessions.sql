-- Persist chatbot conversations per authenticated user and class.
-- The backend accesses these tables with service_role after validating
-- the caller's class ownership or student membership.

begin;

create table if not exists public.chat_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  class_id uuid not null references public.classes(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint chat_sessions_user_class_unique unique (user_id, class_id),
  constraint chat_sessions_id_user_class_unique unique (id, user_id, class_id)
);

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  session_id uuid not null,
  user_id uuid not null,
  class_id uuid not null,
  role text not null check (role in ('user', 'assistant')),
  content text not null check (length(btrim(content)) > 0),
  created_at timestamptz not null default now(),
  constraint chat_messages_session_scope_fk
    foreign key (session_id, user_id, class_id)
    references public.chat_sessions (id, user_id, class_id)
    on delete cascade
);

create index if not exists chat_messages_session_id_id_idx
  on public.chat_messages (session_id, id desc);

create index if not exists chat_sessions_user_class_idx
  on public.chat_sessions (user_id, class_id);

alter table public.chat_sessions enable row level security;
alter table public.chat_messages enable row level security;

-- Chat records are accessed only through authenticated backend endpoints.
-- The backend uses the service_role key after checking user + class access.
revoke all on table public.chat_sessions, public.chat_messages
  from public, anon, authenticated;
grant select, insert, update, delete on table public.chat_sessions,
  public.chat_messages to service_role;
grant usage, select on sequence public.chat_messages_id_seq to service_role;

commit;
